// Project real country shapes (Natural Earth via world-atlas) into SVG paths for a video, offline.
//
//   node map_paths.mjs <out.js> <view.json>
//
// view.json: { "name": "latam", "res": "50m", "box": [x0, y0, x1, y1],         (screen rect to fill)
//              "extent": [[lonW, latS], [lonE, latN]],                       (area to fit in the rect)
//              "projection": "naturalEarth1" | "mercator" | "equalEarth" }
// Appends window.MAPS[name] = { paths: { "<Country name>": "M…" }, centroid: { name: [x, y] },
// bbox: { name: [x0, y0, x1, y1] } } to <out.js> (creates it if missing; re-running a view replaces it).
// Load the out file in index.html before plan.js; anim.js `MapView` draws it.
import fs from 'node:fs'; import vm from 'node:vm'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url)), geo = path.join(here, '..', 'assets', 'geo');
const ctx = { self: {}, window: {} }; ctx.globalThis = ctx; vm.createContext(ctx);
for (const f of ['d3-array.min.js', 'd3-geo.min.js', 'topojson-client.min.js']) vm.runInContext(fs.readFileSync(path.join(geo, f), 'utf8'), ctx);
const d3 = ctx.d3, topojson = ctx.topojson;
const [out, viewFile] = process.argv.slice(2);
const view = JSON.parse(fs.readFileSync(viewFile, 'utf8'));
const topo = JSON.parse(fs.readFileSync(path.join(geo, `countries-${view.res || '50m'}.json`), 'utf8'));
const feats = topojson.feature(topo, topo.objects.countries).features;
const [x0, y0, x1, y1] = view.box;
const proj = d3['geo' + (view.projection || 'naturalEarth1').replace(/^./, c => c.toUpperCase())]();
const [[w, s], [e, n]] = view.extent;
// fit a grid of points over the extent (a lon/lat box as a polygon is ambiguous about its inside)
const grid = [];
for (let i = 0; i <= 8; i++) for (let j = 0; j <= 8; j++) grid.push([w + (e - w) * i / 8, s + (n - s) * j / 8]);
proj.fitExtent([[x0, y0], [x1, y1]], { type: 'MultiPoint', coordinates: grid });
const gp = d3.geoPath(proj).digits(1);
const clip = d3.geoClipRectangle(x0 - 60, y0 - 60, x1 + 60, y1 + 60);
const gpc = d3.geoPath({ stream: s2 => proj.stream(clip(s2)) }).digits(1);
const M = { paths: {}, centroid: {}, bbox: {} };
for (const f of feats) {
  const name = f.properties.name;
  const [[a, b], [c, d]] = gp.bounds(f);
  if (!isFinite(a) || c < x0 - 60 || a > x1 + 60 || d < y0 - 60 || b > y1 + 60) continue;   // off screen
  const p = gpc(f);
  if (!p) continue;
  M.paths[name] = p;
  // label point: centroid of the largest polygon (mainland), so islands don't pull it into the sea
  let best = f, area = -1;
  if (f.geometry.type === 'MultiPolygon') for (const poly of f.geometry.coordinates) {
    const g = { type: 'Polygon', coordinates: poly }, ar = d3.geoArea(g);
    if (ar > area) { area = ar; best = g; }
  }
  M.centroid[name] = gp.centroid(best).map(v => +v.toFixed(1));
  M.bbox[name] = [a, b, c, d].map(v => +v.toFixed(1));
}
let txt = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '// generated by scripts/map_paths.mjs (Natural Earth via world-atlas)\nwindow.MAPS = window.MAPS || {};\n';
txt = txt.replace(new RegExp(`\\nwindow\\.MAPS\\[${JSON.stringify(view.name).replace(/[[\]]/g, '\\$&')}\\] = .*\\n`), '\n');
txt += `window.MAPS[${JSON.stringify(view.name)}] = ${JSON.stringify(M)};\n`;
fs.writeFileSync(out, txt);
console.log(view.name, Object.keys(M.paths).length, 'countries,', (JSON.stringify(M).length / 1024).toFixed(0), 'KB');
