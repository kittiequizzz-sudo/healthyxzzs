# Writes sizes.js (cut-out sizes + brain-region centroids) from cut/*.png.
import glob, json, os
from PIL import Image
import numpy as np
SZ, CEN = {}, {}
for f in sorted(glob.glob('cut/*.png')):
    n = os.path.basename(f)[:-4]; im = Image.open(f); SZ[n] = list(im.size)
    if n.split('_')[0] in ('lobe', 'limb', 'cor') and not n.endswith('_dim'):
        a = np.array(im.convert('RGBA'))[:, :, 3] > 128; ys, xs = np.nonzero(a); CEN[n] = [int(xs.mean()), int(ys.mean())]
open('sizes.js', 'w').write('// cut-out sizes and region centroids (px), generated by mksizes.py from cut/*.png\nconst SZ = ' + json.dumps(SZ) + ';\nconst CEN = ' + json.dumps(CEN) + ';\n')
print(len(SZ), CEN)
